#!/usr/bin/env node
/**
 * Generate website/docs/pages-index.md — markdown list of every docs page.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const docsRoot = path.resolve(__dirname, '../docs');
const outputPath = path.join(docsRoot, 'pages-index.md');

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    if (entry.name === 'pages-index.md') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.(md|mdx)$/i.test(entry.name)) out.push(full);
  }
  return out;
}

function parseTitle(text, fallback) {
  if (text.startsWith('---')) {
    const end = text.indexOf('\n---', 3);
    if (end !== -1) {
      const block = text.slice(4, end);
      const m = block.match(/^title:\s*(.+)$/m);
      if (m) return m[1].trim().replace(/^["']|["']$/g, '');
    }
  }
  const h = text.match(/^#\s+(.+)$/m);
  return h ? h[1].trim() : fallback;
}

const files = walk(docsRoot).sort();
const lines = [
  '---',
  'sidebar_position: 99',
  'title: All docs pages',
  'description: Auto-generated index of documentation pages.',
  '---',
  '',
  '# All docs pages',
  '',
  'Auto-generated by `website/scripts/generate-docs-index.mjs`. Do not edit by hand.',
  '',
];

for (const full of files) {
  const rel = path.relative(docsRoot, full).replace(/\\/g, '/');
  const title = parseTitle(fs.readFileSync(full, 'utf8'), rel);
  lines.push(`- [${title}](./${rel})`);
}
lines.push('');
fs.writeFileSync(outputPath, lines.join('\n'));
console.log(`Wrote ${outputPath} (${files.length} pages)`);
